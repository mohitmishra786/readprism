#!/usr/bin/env python
"""Fast vs large model on real articles, for the #225 quality check.

Summarizes the openly licensed pages in tests/fixtures/real_pages with the
fast model and the large model through this instance's LLM settings, checks
each result mechanically (valid JSON, headline <= 15 words, a 2-3 sentence
brief, topics present), and writes the two side by side for a person to
grade:

    cd backend && python scripts/summary_spot_check.py --n 50 --out ../docs/eval/summary-models.md

Each article costs two model calls on your LLM key.
"""

from __future__ import annotations

import argparse
import asyncio
import gzip
import json
import re
import time
from pathlib import Path

PAGES = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "real_pages"


def articles(n: int) -> list[tuple[str, str, str]]:
    """(id, url, text), round-robin across sources so every source is in."""
    manifest = json.loads((PAGES / "manifest.json").read_text())
    by_source: dict[str, list[dict]] = {}
    for row in manifest:
        by_source.setdefault(row["source"], []).append(row)
    picked: list[dict] = []
    while len(picked) < n and any(by_source.values()):
        for rows in by_source.values():
            if rows and len(picked) < n:
                picked.append(rows.pop(0))
    out = []
    for row in picked:
        text = gzip.decompress((PAGES / f"{row['id']}.txt.gz").read_bytes()).decode()
        out.append((row["id"], row["url"], text))
    return out


def checks(result) -> dict[str, bool]:
    if result is None:
        return {"json": False, "headline": False, "brief": False, "topics": False}
    sentences = [s for s in re.split(r"(?<=[.!?])\s+", result.brief.strip()) if s]
    return {
        "json": True,
        "headline": 0 < len(result.headline.split()) <= 15,
        "brief": 2 <= len(sentences) <= 3,
        "topics": bool(result.topic_clusters),
    }


async def main(n: int, out: Path) -> int:
    from app.config import get_settings
    from app.services.summarization.groq_client import LLMSummarizer

    s = get_settings()
    if not s.llm_configured:
        print("No LLM configured (LLM_API_KEY).")
        return 1
    models = {"fast": s.llm_model_fast, "large": s.llm_model_primary}
    rows = []
    for article_id, url, text in articles(n):
        title = text.split(".")[0][:80]
        row = {"id": article_id, "url": url}
        for label, model in models.items():
            s.llm_model_summary = model
            started = time.perf_counter()
            result = await LLMSummarizer().summarize(title, text)
            row[label] = {
                "seconds": round(time.perf_counter() - started, 1),
                "checks": checks(result),
                "headline": result.headline if result else "",
                "brief": result.brief if result else "",
            }
        rows.append(row)
        print(article_id, {k: all(row[k]["checks"].values()) for k in models})

    def rate(label: str, key: str) -> str:
        ok = sum(r[label]["checks"][key] for r in rows)
        return f"{ok}/{len(rows)}"

    lines = [
        "# Summary models: fast vs large (#225)",
        "",
        f"{len(rows)} openly licensed articles from `tests/fixtures/real_pages`, summarized by "
        f"`{models['fast']}` (fast) and `{models['large']}` (large) with the production prompt. "
        f"Generated by `backend/scripts/summary_spot_check.py` on {time.strftime('%Y-%m-%d')}.",
        "",
        "## Mechanical checks",
        "",
        "| Check | Fast | Large |",
        "|---|---|---|",
    ]
    for key, name in (
        ("json", "Valid JSON"),
        ("headline", "Headline of 15 words or fewer"),
        ("brief", "Brief of 2-3 sentences"),
        ("topics", "Topics present"),
    ):
        lines.append(f"| {name} | {rate('fast', key)} | {rate('large', key)} |")
    median = {k: sorted(r[k]["seconds"] for r in rows)[len(rows) // 2] for k in models}
    lines.append(f"| Median seconds | {median['fast']} | {median['large']} |")
    lines += [
        "",
        "## Human grading",
        "",
        "For each article, mark which brief is more accurate and useful: F, L, or = (equal).",
        "",
    ]
    for r in rows:
        lines += [
            f"### {r['id']}: <{r['url']}>",
            "",
            f"- **Fast:** {r['fast']['headline']}. {r['fast']['brief']}",
            f"- **Large:** {r['large']['headline']}. {r['large']['brief']}",
            "- **Better:** _",
            "",
        ]
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--n", type=int, default=50)
    parser.add_argument("--out", type=Path, default=Path("summary-models.md"))
    args = parser.parse_args()
    raise SystemExit(asyncio.run(main(args.n, args.out)))
